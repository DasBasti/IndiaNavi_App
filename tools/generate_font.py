#!/usr/bin/env python3
"""Converts the 8x8 font of the IndiaNavi firmware into modules/font8x8.js.

Usage: tools/generate_font.py [path to IndiaNavi_Firmware/lib/Platinenmacher/fonts/font8x8.c]

The firmware stores every character as 8 rows of one byte, bit 0 is the left pixel. The first
character is the space (0x20).
"""
import os
import re
import sys

source = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    os.path.dirname(__file__), '..', '..', 'IndiaNavi_Firmware', 'lib', 'Platinenmacher', 'fonts', 'font8x8.c')
target = os.path.join(os.path.dirname(__file__), '..', 'modules', 'font8x8.js')

# one character per line: 8 bytes and a comment with its code point
glyphs = [[int(value, 16) for value in re.findall(r'0x([0-9a-fA-F]{2})', line.split('//')[0])]
          for line in open(source) if '// U+' in line]
assert all(len(glyph) == 8 for glyph in glyphs), 'every character has 8 rows'
first = 0x20

with open(target, 'w') as out:
    out.write('// Generated by tools/generate_font.py from the 8x8 font of the IndiaNavi firmware. Do not edit.\n')
    out.write('// 8 rows per character, bit 0 is the left pixel. The first character is the space.\n\n')
    out.write(f'export const FIRST_CHAR = 0x{first:02x};\n')
    out.write(f'export const LAST_CHAR = 0x{first + len(glyphs) - 1:02x};\n\n')
    out.write('export const GLYPHS = [\n')
    for index, glyph in enumerate(glyphs):
        code = first + index
        out.write('  [' + ', '.join(f'0x{byte:02x}' for byte in glyph) + f'], // {code:#04x}\n')
    out.write('];\n')
